const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH ?? 'playwright')
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
const url = process.argv[2] ?? 'http://127.0.0.1:5173/'
const out = path.resolve(process.argv[3] ?? 'output/playwright/koharu')
await mkdir(out, { recursive: true })
const checks = [], errors = [], requests = []
const check = (name, passed, detail) => { checks.push({name, passed:!!passed, detail}); if (!passed) throw new Error(`${name}: ${JSON.stringify(detail)}`) }
const distance = (a,b) => Math.hypot(...a.map((v,i)=>v-b[i]))
const browser = await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']})
const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1})
page.on('pageerror', e=>errors.push(e.message))
page.on('console', m=>{if(m.type()==='error')errors.push(m.text())})
page.on('request', r=>requests.push(r.url()))
const camera = async()=> (await page.locator('canvas').getAttribute('data-camera')).split(',').map(Number)
const shot = async name => page.screenshot({path:path.join(out,name)})
try {
  await page.goto(url); await page.waitForLoadState('networkidle')
  await page.locator('canvas[data-ready="true"]').waitFor({timeout:30000})
  await page.waitForFunction(()=>Number(document.querySelector('canvas').dataset.elapsed)>2)
  check('WebGL scene renders',true)
  check('No interface elements',await page.locator('button,input,select,nav,header,footer,h1').count()===0)
  const visibleCopy = await page.evaluate(()=>[...document.querySelectorAll('main *')].filter(e=>!e.closest('canvas')&&e.children.length===0&&getComputedStyle(e).visibility!=='hidden').map(e=>e.innerText??'').join('').trim())
  check('No visible HTML copy',visibleCopy==='',visibleCopy)
  check('Canvas fills desktop viewport', (await page.locator('canvas').boundingBox()).width===1440)
  await shot('01-overview.png')
  const initial=await camera()
  await page.mouse.move(850,450);await page.mouse.down();await page.mouse.move(1140,490,{steps:24});await page.mouse.up()
  await page.waitForFunction(before=>Math.hypot(...document.querySelector('canvas').dataset.camera.split(',').map((n,i)=>Number(n)-before[i]))>2,initial)
  check('Drag rotates the model',distance(initial,await camera())>2,await camera());await shot('02-orbit.png')
  const zoom=Number(await page.locator('canvas').getAttribute('data-zoom'))
  for (let i=0;i<8;i++) { await page.mouse.wheel(0,-180); await page.waitForTimeout(60) }
  await page.waitForFunction(before=>Number(document.querySelector('canvas').dataset.zoom)>before*1.1,zoom)
  check('Wheel zooms in',Number(await page.locator('canvas').getAttribute('data-zoom'))>zoom*1.1)
  await shot('03-interior-detail.png')
  await page.mouse.dblclick(800,450);await page.waitForTimeout(400)
  check('Double click restores camera',distance(initial,await camera())<.1,await camera())
  check('Reset clears zoom inertia',Math.abs(Number(await page.locator('canvas').getAttribute('data-zoom'))-zoom)<.1)
  const beforePan=await camera()
  await page.mouse.move(850,450);await page.mouse.down({button:'right'});await page.mouse.move(970,510,{steps:18});await page.mouse.up({button:'right'});await page.waitForTimeout(350)
  check('Right drag pans',distance(beforePan,await camera())>.3,await camera())
  await page.mouse.dblclick(800,450)
  await page.mouse.move(900,440);await page.mouse.down();await page.mouse.move(100,440,{steps:50});await page.mouse.up();await page.waitForTimeout(350)
  check('Orbit reaches the rear', (await camera())[2]<0,await camera());await shot('04-rear.png')
  await page.mouse.dblclick(800,450)
  await page.waitForFunction(()=>Number(document.querySelector('canvas').dataset.door)>.7,null,{timeout:23000})
  check('Automatic doors open',true);await shot('05-door-open.png')
  await page.waitForFunction(()=>Number(document.querySelector('canvas').dataset.door)<.1,null,{timeout:12000})
  check('Automatic doors close',true)
  const signal=await page.locator('canvas').getAttribute('data-signal')
  await page.waitForFunction(s=>document.querySelector('canvas').dataset.signal!==s,signal,{timeout:15000});check('Traffic signal changes',true)
  const elapsed=Number(await page.locator('canvas').getAttribute('data-elapsed'))
  await page.waitForFunction(t=>Number(document.querySelector('canvas').dataset.elapsed)>t+.5,elapsed);check('Weather keeps advancing',true)
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(600);await shot('06-mobile.png')
  check('Portrait canvas fits', (await page.locator('canvas').boundingBox()).width===390)
  check('Portrait page has no overflow or UI',await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth)&&await page.locator('button,input,select').count()===0)
  await page.setViewportSize({width:1440,height:1000});await page.mouse.dblclick(800,450);await page.waitForTimeout(600);await shot('07-final.png')
  const external=requests.filter(u=>!u.startsWith(new URL(url).origin)&&!u.startsWith('data:')&&!u.startsWith('blob:'))
  check('No external asset requests',external.length===0,external)
  check('No runtime or shader errors',errors.length===0,errors)
} finally {
  const report={url,passed:checks.filter(c=>c.passed).length,checks,errors,diagnostics:await page.locator('canvas').evaluate(c=>({...c.dataset}))}
  await writeFile(path.join(out,'results.json'),JSON.stringify(report,null,2))
  console.log(JSON.stringify(report,null,2));await browser.close()
}
